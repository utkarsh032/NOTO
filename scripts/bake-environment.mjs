#!/usr/bin/env node
/**
 * Writes the chosen environment overlay into the module the desktop bundle
 * carries.
 *
 *   node scripts/bake-environment.mjs --environment Production --channel stable
 *
 * One implementation, two callers: `noto-release.ps1` for a local release and
 * `.github/workflows/desktop.yml` for a CI one. While the baking lived only in
 * the PowerShell script, every package CI produced silently carried the
 * committed Development defaults - the wrong update feed, with nothing in the
 * artifact's name to say so.
 *
 * The overlay set is whatever is on disk. Nothing here enumerates the
 * environments, so adding an overlay file is all it takes to add one.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OVERLAY_DIR = path.join(root, 'apps', 'desktop', 'environments');
const TARGET = path.join(root, 'apps', 'desktop', 'src', 'generated', 'environment.ts');

const CHANNELS = ['stable', 'beta', 'nightly'];
const REQUIRED = [
  'environment',
  'description',
  'buildEnv',
  'defaultChannel',
  'updateFeedUrl',
  'webAppUrl',
];

function fail(message) {
  process.stderr.write(`bake-environment: ${message}\n`);
  process.exit(1);
}

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!argv[i].startsWith('--')) fail(`unexpected argument "${argv[i]}"`);
    args[argv[i].slice(2)] = argv[i + 1];
  }
  return args;
}

function overlayNames() {
  if (!existsSync(OVERLAY_DIR)) return [];
  return readdirSync(OVERLAY_DIR)
    .filter((name) => /^noto\..+\.json$/.test(name))
    .map((name) => name.replace(/^noto\./, '').replace(/\.json$/, ''));
}

const { environment, channel } = parseArgs(process.argv.slice(2));

if (!environment) {
  fail(
    `--environment is required. Available: ${overlayNames().join(', ') || '(no overlays found)'}`,
  );
}

const overlayPath = path.join(OVERLAY_DIR, `noto.${environment}.json`);
if (!existsSync(overlayPath)) {
  fail(
    `no overlay for "${environment}" at ${overlayPath}.\n` +
      `  Available: ${overlayNames().join(', ') || '(none)'}`,
  );
}

let overlay;
try {
  overlay = JSON.parse(readFileSync(overlayPath, 'utf8'));
} catch (error) {
  fail(`noto.${environment}.json is not valid JSON: ${error.message}`);
}

for (const field of REQUIRED) {
  if (!(field in overlay)) {
    fail(`noto.${environment}.json is missing the required field "${field}".`);
  }
}

const resolvedChannel = channel || overlay.defaultChannel;
if (!CHANNELS.includes(resolvedChannel)) {
  fail(`"${resolvedChannel}" is not a valid channel. Expected one of: ${CHANNELS.join(', ')}`);
}

/**
 * Escapes a value for a single-quoted TypeScript literal.
 *
 * JSON string escaping already covers backslashes, control characters and
 * anything else that would break out of a string; the only difference is the
 * quote character, so the JSON form is reused and the quotes swapped. A URL
 * containing an apostrophe is unlikely, but a generated file that does not
 * parse would fail the build long after the cause stopped being obvious.
 */
function literal(value) {
  const json = JSON.stringify(String(value));
  return json.slice(1, -1).replace(/'/g, "\\'");
}

// Prettier runs over this file during `pnpm format:check`, which a release
// executes moments after writing it. The trailing newline below is not
// cosmetic: without it, the release aborts on its own generated output.
const contents = `/**
 * Build environment baked in at package time.
 *
 * GENERATED by scripts/bake-environment.mjs - do not edit. The committed
 * contents of this file are the Development defaults; a release build rewrites
 * it, and \`noto-release.ps1\` restores it when the build finishes.
 *
 * This exists as a generated module rather than as environment variables
 * because \`process.env\` is a property of the machine that ran the build, not
 * of the artifact it produced. A packaged application launched from a user's
 * Start menu inherits none of it - so the update feed a release was built
 * against has to travel inside the bundle.
 */

/** Overlay this build was made from - see apps/desktop/environments. */
export const BUILD_ENVIRONMENT = '${literal(overlay.environment)}';

/** Update channel baked in at package time. */
export const BUILD_CHANNEL = '${literal(resolvedChannel)}';

/** Static update feed for non-stable channels. Empty disables updating. */
export const UPDATE_FEED_URL = '${literal(overlay.updateFeedUrl)}';

/** Where the web application lives, for links out of the desktop app. */
export const WEB_APP_URL = '${literal(overlay.webAppUrl)}';
`;

writeFileSync(TARGET, contents, 'utf8');

// Printed as KEY=value so that a shell can consume it, and so that a CI log
// records exactly what was baked into the artifact it is about to publish.
process.stdout.write(`NOTO_BUILD_ENVIRONMENT=${overlay.environment}\n`);
process.stdout.write(`NOTO_BUILD_ENV=${overlay.buildEnv}\n`);
process.stdout.write(`NOTO_UPDATE_CHANNEL=${resolvedChannel}\n`);
process.stdout.write(`NOTO_UPDATE_FEED_URL=${overlay.updateFeedUrl}\n`);
process.stdout.write(`NOTO_WEB_APP_URL=${overlay.webAppUrl}\n`);
