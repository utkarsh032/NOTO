/**
 * Packages the Noto interface into the iOS application bundle.
 *
 * The iOS counterpart of `with-android-webapp.cjs`. The built interface is
 * copied to `ios/<Project>/webapp` and added to the Xcode project as a *folder
 * reference* — one entry for the whole directory, copied into `Noto.app/webapp`
 * as it is. A group of individual files would flatten `assets/` into the bundle
 * root and break every relative path in `index.html`, and it would need editing
 * whenever the build's hashed file names changed.
 *
 * The WebView then loads `<bundle>/webapp/index.html` (see `NotoWebView.tsx`).
 *
 * `apps/mobile/ios` is regenerated by `expo prebuild`, so both the copy and the
 * project entry are reapplied on every generation.
 */

const path = require('node:path');

const { IOSConfig, withDangerousMod, withXcodeProject } = require('expo/config-plugins');

const { copyInterfaceBuild } = require('./webapp-build.cjs');

const FOLDER = 'webapp';

function withWebappCopy(config) {
  return withDangerousMod(config, [
    'ios',
    (dangerousConfig) => {
      const { platformProjectRoot, projectName } = dangerousConfig.modRequest;
      copyInterfaceBuild(path.join(platformProjectRoot, projectName, FOLDER), 'with-ios-webapp');
      return dangerousConfig;
    },
  ]);
}

function withWebappFolderReference(config) {
  return withXcodeProject(config, (xcodeConfig) => {
    const project = xcodeConfig.modResults;
    const { projectName } = xcodeConfig.modRequest;

    IOSConfig.XcodeUtils.addResourceFileToGroup({
      filepath: path.posix.join(projectName, FOLDER),
      groupName: projectName,
      isBuildFile: true,
      project,
      // Quiet on a second run over the same project, where the entry exists.
      verbose: false,
    });

    /*
     * The helper guesses the file type from the extension, and a directory has
     * none, so it is recorded as `unknown` — which Xcode copies as a single
     * opaque file, or not at all. `folder` is what makes it a folder reference.
     *
     * It also leaves `fileEncoding` and `explicitFileType` unset, which the
     * writer would print as the literal word `undefined`.
     */
    const references = project.pbxFileReferenceSection();
    for (const reference of Object.values(references)) {
      if (typeof reference !== 'object') continue;
      if (IOSConfig.XcodeUtils.unquote(String(reference.name)) !== FOLDER) continue;
      reference.lastKnownFileType = 'folder';
      delete reference.fileEncoding;
      delete reference.explicitFileType;
    }

    return xcodeConfig;
  });
}

module.exports = function withIosWebapp(config) {
  return withWebappFolderReference(withWebappCopy(config));
};
