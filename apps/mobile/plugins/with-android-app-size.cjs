/**
 * Cuts the size of the release APK.
 *
 * The template Expo generates produces a ~104 MB APK, and almost all of it is
 * native code that the phone installing it cannot run. Three things are
 * responsible:
 *
 *   1. One universal APK carries `armeabi-v7a`, `arm64-v8a`, `x86` and
 *      `x86_64`. Every `.so` — React Native, Hermes, fbjni, Fresco, the Expo
 *      modules, SQLite — is in there four times, and they are stored
 *      uncompressed. That is ~75 MB of the total, and roughly three quarters
 *      of it is dead weight on any given device.
 *   2. R8 is off (`android.enableMinifyInReleaseBuilds` defaults to `false`),
 *      so the release `classes.dex` keeps every unreachable class in React
 *      Native, AndroidX and the Expo modules.
 *   3. Fresco's GIF and animated-image codecs are compiled in, though the app
 *      renders no images at all.
 *
 * Measured on a clean `expo prebuild` + `assembleRelease`, this takes the
 * 64-bit APK from 104 MB to 16.0 MB (32-bit: 15.1 MB). Splitting by ABI does
 * most of the work; compressing the libraries does the rest.
 *
 * `apps/mobile/android` is regenerated by `expo prebuild`, so none of this can
 * be a hand-edit of the generated project — it has to be reapplied on every
 * generation, which is what a config plugin is for. Companion to
 * `with-android-release-signing.cjs`.
 */

const { withAppBuildGradle, withGradleProperties } = require('expo/config-plugins');

const MARKER = 'noto.enableAbiSplits';

/**
 * Release-build properties, all read by the generated `app/build.gradle`.
 *
 * `enableMinifyInReleaseBuilds` is the one with teeth: R8 strips unreachable
 * code, and anything reached only by reflection has to be kept by a Proguard
 * rule. React Native, AndroidX and the Expo modules all ship consumer rules for
 * their own reflection, which is why this is safe to turn on — but CI has no
 * device test, so a release build still needs a smoke test on a real phone
 * before it is published. Set this to `false` to rule R8 out when triaging a
 * crash that only reproduces on a release build.
 */
const PROPERTIES = {
  'android.enableMinifyInReleaseBuilds': 'true',
  // Only has an effect with minification on; drops unreferenced resources.
  'android.enableShrinkResourcesInReleaseBuilds': 'true',
  // Compresses the Hermes bytecode bundle in the APK. Costs a decompression at
  // launch and saves a couple of megabytes of download.
  'android.enableBundleCompression': 'true',
  // Noto's mobile UI is text only — it renders no images, so Fresco's animated
  // codecs are pure payload. Turn these back on before adding an <Image>.
  'expo.gif.enabled': 'false',
  'expo.webp.enabled': 'false',
  // Compresses the native libraries inside the APK. This is a deliberate
  // departure from the Android default, and it is a trade, not a free win:
  //
  //   uncompressed (the default)  29.6 MB download, mapped straight out of
  //                               the APK, nothing duplicated on disk
  //   compressed (this)           16.0 MB download, but Android extracts the
  //                               libraries at install, so the phone holds
  //                               them twice and installs are slower
  //
  // Noto's APK is handed out from the download page, where the number people
  // see — and pay for in bandwidth — is the download. That is what tips it.
  // The Play Store is unaffected either way: `bundleRelease` ships an AAB and
  // Play re-packs it per device with its own packaging choice.
  'expo.useLegacyPackaging': 'true',
};

/**
 * Splits the release into one APK per ABI instead of one carrying all four.
 *
 * All four ABIs stay in the list. `x86`/`x86_64` are emulator-only and nobody
 * downloads them, but `expo run:android` installs onto an emulator through the
 * same split, and excluding them would hand it an APK with no library it can
 * load. Packaging a split is cheap — the native code is compiled once either
 * way — so the two unused outputs cost build time, not correctness.
 *
 * `universalApk false`: the combined APK is exactly what this plugin exists to
 * stop shipping. `bundleRelease` builds the Play Store artifact, where Play
 * does the splitting itself, so the release workflow turns this off for that
 * task with `-Pnoto.enableAbiSplits=false`.
 */
const ABI_SPLITS = `
    // Set by \`with-android-app-size.cjs\`. See that plugin for why.
    // Read outside the closure, as the rest of this file does: inside it the
    // delegate is Gradle's split options, not the project.
    def notoAbiSplits = (findProperty('noto.enableAbiSplits') ?: 'true').toBoolean()
    splits {
        abi {
            reset()
            enable notoAbiSplits
            universalApk false
            include 'armeabi-v7a', 'arm64-v8a', 'x86', 'x86_64'
        }
    }

`;

function setProperty(items, key, value) {
  const existing = items.find((item) => item.type === 'property' && item.key === key);
  if (existing) {
    existing.value = value;
    return;
  }
  items.push({ type: 'property', key, value });
}

/**
 * Inserts the splits block into the `android { ... }` block.
 *
 * Anchored on `buildTypes {`, which the Expo template always emits and which
 * sits inside `android { ... }` — so the block lands in the right scope without
 * this having to parse Groovy.
 */
function addAbiSplits(contents) {
  const anchor = /\n(\s*)buildTypes\s*\{/;
  if (!anchor.test(contents)) return null;
  return contents.replace(anchor, (match, indent) => `\n${ABI_SPLITS}${indent}buildTypes {`);
}

module.exports = function withAndroidAppSize(config) {
  const withProperties = withGradleProperties(config, (gradleConfig) => {
    for (const [key, value] of Object.entries(PROPERTIES)) {
      setProperty(gradleConfig.modResults, key, value);
    }
    return gradleConfig;
  });

  return withAppBuildGradle(withProperties, (gradleConfig) => {
    const { modResults } = gradleConfig;

    if (modResults.language !== 'groovy') {
      throw new Error(
        `with-android-app-size expects a Groovy build.gradle, found ${modResults.language}.`,
      );
    }

    // Prebuild can run against an already-generated project.
    if (modResults.contents.includes(MARKER)) return gradleConfig;

    const withSplits = addAbiSplits(modResults.contents);
    if (!withSplits) {
      // Failing here is deliberate. Carrying on would quietly produce the
      // 104 MB universal APK again and say nothing about it.
      throw new Error(
        'with-android-app-size could not find the buildTypes block in app/build.gradle.',
      );
    }

    modResults.contents = withSplits;
    return gradleConfig;
  });
};
